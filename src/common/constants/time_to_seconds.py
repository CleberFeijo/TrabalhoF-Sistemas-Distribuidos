MINUTE_TO_SECONDS = 60
"Constante contendo um minuto convertido em segundos."

HOUR_TO_SECONDS = MINUTE_TO_SECONDS * 60
"Constante contendo uma hora convertida em segundos."

DAY_TO_SECONDS = HOUR_TO_SECONDS * 24
"Constante contendo um dia convertido em segundos."

MONTH_TO_SECONDS = DAY_TO_SECONDS * 30
"Constante contendo um mês comercial (30 dias) convertido em segundos."

YEAR_TO_SECONDS = MONTH_TO_SECONDS * 12
"Constante contendo um ano comercial (360 dias) convertido em segundos"
